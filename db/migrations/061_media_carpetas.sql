-- Migración 061: carpetas para el contenido privado (media_carpetas + media.carpeta_id).
-- Mismo esquema que worker/migracion_media_carpetas.sql en D1. Sin esta tabla,
-- la secundaria no puede listar ni crear carpetas (GET/POST /api/media/carpetas).
BEGIN;

CREATE TABLE IF NOT EXISTS media_carpetas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre TEXT NOT NULL,
  creada_por_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  created_at TEXT NOT NULL DEFAULT (CURRENT_TIMESTAMP)
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_media_carpetas_nombre ON media_carpetas(LOWER(nombre));

ALTER TABLE media ADD COLUMN IF NOT EXISTS carpeta_id INTEGER REFERENCES media_carpetas(id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS idx_media_carpeta ON media(carpeta_id);

COMMIT;
