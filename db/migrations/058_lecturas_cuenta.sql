-- Migración 058: guardadas para leer luego e historial de lectura de los
-- lectores (mismo esquema que worker/migracion_lecturas_cuenta.sql en D1).
--
-- Sin estas tablas, sync/incremental.mjs no podría replicar las filas de D1 y
-- las peticiones de lectores que cayeran en el worker secundario durante un
-- failover no tendrían dónde leer/escribir.
--
-- Las FK son DEFERRABLE INITIALLY DEFERRED (igual que en 057) para que el
-- sincronizador no falle si en un mismo lote llega la fila antes que su padre.
BEGIN;

CREATE TABLE IF NOT EXISTS reader_saved_articles (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reader_id INTEGER NOT NULL REFERENCES readers(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
  article_id INTEGER NOT NULL REFERENCES articles(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
  created_at TEXT NOT NULL DEFAULT (to_char((now() AT TIME ZONE 'UTC'), 'YYYY-MM-DD HH24:MI:SS')),
  UNIQUE (reader_id, article_id)
);
CREATE INDEX IF NOT EXISTS idx_reader_saved_reader_fecha ON reader_saved_articles(reader_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_reader_saved_article ON reader_saved_articles(article_id);

CREATE TABLE IF NOT EXISTS reader_reading_history (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reader_id INTEGER NOT NULL REFERENCES readers(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
  article_id INTEGER NOT NULL REFERENCES articles(id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
  created_at TEXT NOT NULL DEFAULT (to_char((now() AT TIME ZONE 'UTC'), 'YYYY-MM-DD HH24:MI:SS')),
  UNIQUE (reader_id, article_id)
);
CREATE INDEX IF NOT EXISTS idx_reader_history_reader_fecha ON reader_reading_history(reader_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_reader_history_article ON reader_reading_history(article_id);

COMMIT;
